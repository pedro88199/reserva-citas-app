    public List<Cita> listarCitas() {
        List<Cita> citas = new ArrayList<>();
        Connection conn = Database.obtenerConexion();
        if (conn != null) {
            //concatenar nombres y apellidos de paciente y doctor
            String sql = "SELECT CONCAT(p.nombre , ' ' , p.apellido) AS nombrePaciente, CONCAT(d.nombre, ' ' , d.apellido) AS nombreDoctor, d.especialidad, c.fecha, c.hora, c.estado "
                    + "FROM cita c "
                    + "JOIN paciente p ON c.paciente_id = p.id_paciente "
                    + "JOIN doctor d ON c.doctor_id = d.id_doctor "
                    + "JOIN horario h ON d.id_horario = h.id_horario";
            try (PreparedStatement statement = conn.prepareStatement(sql)) {
                ResultSet resultSet = statement.executeQuery();
                while (resultSet.next()) {
                    String nombrePaciente = resultSet.getString("nombrePaciente");
                    String nombreDoctor = resultSet.getString("nombreDoctor");
                    String especialidadDoctor = resultSet.getString("especialidad");
                    String fecha = resultSet.getString("fecha");
                    String hora = resultSet.getString("hora");
                    String estado = resultSet.getString("estado");
                    Cita cita = new Cita(nombrePaciente, nombreDoctor, especialidadDoctor, LocalDate.parse(fecha), hora, estado);
                    citas.add(cita);
                }
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
        llenarTablaCitas(citas);
        return citas;
    }



    private void llenarTablaCitas(List<Cita> citas) {
        DefaultTableModel model = (DefaultTableModel) tblCitas.getModel();
        model.setRowCount(0); // Limpiar la tabla

        for (Cita cita : citas) {
            model.addRow(new Object[]{
                    cita.getNombrePaciente(),
                    cita.getNombreDoctor(),
                    cita.getEspecialidadDoctor(),
                    cita.getFecha(),
                    cita.getHora(),
                    cita.getEstado()
            });
        }
    }


