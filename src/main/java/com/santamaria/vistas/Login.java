    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
       
        String usuario = txtUsuario.getText();
    String contraseña = String.valueOf(txtContraseña.getPassword());

    if (usuario.isEmpty() || contraseña.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Por favor, complete todos los campos para iniciar sesión.", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
        return; 
    }

    // Crear un objeto de la clase CLogin
        CLogin objetoLogin = new CLogin();
        if (objetoLogin.validaUsuario(txtUsuario, txtContraseña)) {
        // Si la validación es exitosa, abrir la ventana Menu_Principal
        Menu_Principal objetoMenu = new Menu_Principal();
        objetoMenu.setVisible(true);

    }
        this.dispose(); 
    }//GEN-LAST:event_btnIngresarActionPerformed

