    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        
        String ingUsuario = txtUsuario.getText();
    String ingContrasenia = String.valueOf(txtContraseña.getPassword());
    String confirmaContra = String.valueOf(txtCContraseña.getPassword());
    String nombre = txtNombre.getText();
    String correo = txtCorreo.getText();

    if (ingUsuario.isEmpty() || ingContrasenia.isEmpty() || confirmaContra.isEmpty() || nombre.isEmpty() || correo.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Por favor, complete todos los campos para registrarse.", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
        return;
    }

    Registro registroFrame = new Registro();
    registroFrame.setVisible(true);

    this.setVisible(false);
        
    }//GEN-LAST:event_btnRegistrarActionPerformed

