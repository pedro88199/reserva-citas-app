    private List<Paciente> listarPacientes() {
    List<Paciente> pacientes = new ArrayList<>();
    Connection conn = Database.obtenerConexion();
    if (conn != null) {
        String sql = "SELECT p.nombre AS nombres, p.apellido AS apellidos, p.especialidadDeseada AS especialidadRequerida "
                   + "FROM paciente p "
                   + "LEFT JOIN cita c ON p.id_paciente = c.paciente_id "
                   + "WHERE c.id_cita IS NULL";
        try (PreparedStatement statement = conn.prepareStatement(sql)) {
            ResultSet resultSet = statement.executeQuery();
            while (resultSet.next()) {
                String nombre = resultSet.getString("nombres");
                String apellido = resultSet.getString("apellidos");
                String especialidad = resultSet.getString("especialidadRequerida");
                Paciente paciente = new Paciente(nombre, apellido, especialidad);
                pacientes.add(paciente);
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
    llenarTablaPacientes(pacientes);
    return pacientes;
}

    private void llenarTablaPacientes(List<Paciente> pacientes) {
        DefaultTableModel model = (DefaultTableModel) tblPacientes.getModel();
        model.setRowCount(0); // Limpiar la tabla

        for (Paciente paciente : pacientes) {
            model.addRow(new Object[]{
                    paciente.getNombre(),
                    paciente.getApellido(),
                    paciente.getEspecialidadDeseada()
            });
        }
    }
    
    public void guardarCitasEnBaseDeDatos(List<Cita> citas) {
        Connection conn = Database.obtenerConexion();
        if (conn != null) {
            String sql = "INSERT INTO cita (paciente_id, doctor_id, fecha, hora, estado) VALUES (?, ?, ?, ?, ?)";
            System.out.println(sql);
            try (PreparedStatement statement = conn.prepareStatement(sql)) {
                for (Cita cita : citas) {
                    System.out.println(cita);
                    statement.setInt(1, cita.getIdPaciente());
                    statement.setInt(2, cita.getIdDoctor());
                    statement.setDate(3, java.sql.Date.valueOf(cita.getFecha()));
                    statement.setString(4, cita.getHorario().getHoraInicio());
                    statement.setString(5, cita.getEstado());
                    statement.addBatch(); // Añadir a batch para ejecutar todas las inserciones a la vez
                }
                statement.executeBatch(); // Ejecutar batch de inserciones
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }



